package com.l2t.lcj;

public class SumOfTwoNumbers {

    public static void main(String[] args) {
        int num1 = 10;
        int num2 = 20;
        int sum = num1 + num2;
        double avg = sum / 2.0;
        System.out.println("The sum of " + num1 + " and " + num2 + " is " + sum);
        System.out.println("Average is " + avg);
    }
}
